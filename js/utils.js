  /* ---- Keyboard shortcut handler ---- */
  const shortcuts = {};
  function registerShortcut(combo, callback, description) {
    shortcuts[combo] = { callback, description };
  }
  function initShortcuts() {
    document.addEventListener('keydown', (e) => {
      const key = [];
      if (e.ctrlKey || e.metaKey) key.push('Ctrl');
      if (e.shiftKey) key.push('Shift');
      if (e.altKey) key.push('Alt');
      if (e.key.length === 1) key.push(e.key.toUpperCase());
      else if (e.key === 'F2') key.push('F2');
      else if (e.key === 'F3') key.push('F3');
      else if (e.key === 'Escape') key.push('Esc');
      else return;
      const combo = key.join('+');
      if (shortcuts[combo]) {
        e.preventDefault();
        shortcuts[combo].callback();
      }
    });
  }

