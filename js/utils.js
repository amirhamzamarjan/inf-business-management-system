  /* ---- Simple ZIP builder ---- */
  function createZip(files) {
    // Minimal ZIP implementation for text files
    const encoder = new TextEncoder();
    const parts = [];
    const centralDir = [];
    let offset = 0;

    files.forEach(({ name, content }) => {
      const nameBytes = encoder.encode(name);
      const dataBytes = typeof content === 'string' ? encoder.encode(content) : content;
      const crc = crc32(dataBytes);

      // Local file header
      const header = new ArrayBuffer(30 + nameBytes.length);
      const hv = new DataView(header);
      hv.setUint32(0, 0x04034b50, true); // signature
      hv.setUint16(4, 20, true); // version
      hv.setUint16(6, 0, true);  // flags
      hv.setUint16(8, 0, true);  // compression: none
      hv.setUint16(10, 0, true); // mod time
      hv.setUint16(12, 0, true); // mod date
      hv.setUint32(14, crc, true);
      hv.setUint32(18, dataBytes.length, true); // compressed
      hv.setUint32(22, dataBytes.length, true); // uncompressed
      hv.setUint16(26, nameBytes.length, true);
      hv.setUint16(28, 0, true); // extra length
      new Uint8Array(header).set(nameBytes, 30);

      // Central dir entry
      const cent = new ArrayBuffer(46 + nameBytes.length);
      const cv = new DataView(cent);
      cv.setUint32(0, 0x02014b50, true);
      cv.setUint16(4, 20, true);
      cv.setUint16(6, 20, true);
      cv.setUint16(8, 0, true);
      cv.setUint16(10, 0, true);
      cv.setUint16(12, 0, true);
      cv.setUint16(14, 0, true);
      cv.setUint32(16, crc, true);
      cv.setUint32(20, dataBytes.length, true);
      cv.setUint32(24, dataBytes.length, true);
      cv.setUint16(28, nameBytes.length, true);
      cv.setUint16(30, 0, true);
      cv.setUint16(32, 0, true);
      cv.setUint16(34, 0, true);
      cv.setUint16(36, 0, true);
      cv.setUint32(38, 0x20, true); // external attrs
      cv.setUint32(42, offset, true); // local header offset
      new Uint8Array(cent).set(nameBytes, 46);

      parts.push(header, dataBytes);
      centralDir.push(cent);
      offset += 30 + nameBytes.length + dataBytes.length;
    });

    const centralDirOffset = offset;
    let centralDirSize = 0;
    centralDir.forEach(c => { parts.push(c); centralDirSize += c.byteLength; });

    // End of central dir
    const eocd = new ArrayBuffer(22);
    const ev = new DataView(eocd);
    ev.setUint32(0, 0x06054b50, true);
    ev.setUint16(4, 0, true);
    ev.setUint16(6, 0, true);
    ev.setUint16(8, files.length, true);
    ev.setUint16(10, files.length, true);
    ev.setUint32(12, centralDirSize, true);
    ev.setUint32(16, centralDirOffset, true);
    ev.setUint16(20, 0, true);
    parts.push(eocd);

    return new Blob(parts, { type: 'application/zip' });
  }

  function crc32(bytes) {
    let c, table = crc32.table || (crc32.table = (() => {
      const t = new Uint32Array(256);
      for (let n = 0; n < 256; n++) {
        c = n;
        for (let k = 0; k < 8; k++) c = (c & 1) ? (0xEDB88320 ^ (c >>> 1)) : (c >>> 1);
        t[n] = c;
      }
      return t;
    })());
    c = 0xFFFFFFFF;
    for (let i = 0; i < bytes.length; i++) c = table[(c ^ bytes[i]) & 0xFF] ^ (c >>> 8);
    return (c ^ 0xFFFFFFFF) >>> 0;
  }

